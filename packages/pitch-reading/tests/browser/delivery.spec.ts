import { test, expect } from '@playwright/test';

test.use({video:{mode:'on',size:{width:1280,height:900}},viewport:{width:1280,height:900}});
test('delivery inspector shows windup, plant, release and follow-through from close views',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/?lab=1');await page.locator('#mode-lab').click();
  await page.locator('[data-review="delivery"]').click();
  await expect(page.locator('#delivery-phase')).toBeVisible();
  await expect(page.locator('#delivery-phase')).toContainText('투구 4');
  await expect(page.locator('#timeline-time')).toContainText('-1.684s');
  await page.locator('.viewport-shell').scrollIntoViewIfNeeded();
  await page.locator('[data-delivery-event="1"]').click();
  await page.locator('[data-view="delivery-side"]').click();
  await page.screenshot({path:'test-results/delivery-knee-lift.png',fullPage:true});
  await page.locator('[data-delivery-event="2"]').click();
  await expect(page.locator('#delivery-phase-label')).toHaveText('착지 · 몸통 회전');
  await page.locator('[data-delivery-event="4"]').click();
  await expect(page.locator('#timeline-time')).toContainText('+0.000s');
  await page.locator('[data-view="delivery-front"]').click();
  await page.screenshot({path:'test-results/delivery-release.png',fullPage:true});
  await page.locator('[data-delivery-event="5"]').click();
  await page.locator('[data-view="delivery-back"]').click();
  await expect(page.locator('#delivery-phase-label')).toHaveText('감속 · 팔로스루');
  await page.screenshot({path:'test-results/delivery-follow-through.png',fullPage:true});
  await page.locator('[data-view="delivery-front"]').click();
  await page.locator('[data-delivery-event="0"]').click();
  await page.locator('#lab-play').click();
  await expect(page.locator('#lab-play')).toHaveAttribute('aria-label','궤적 재생',{timeout:12000});
  await page.locator('[data-pitcher="lefty"]').click();
  await expect(page.locator('#delivery-motion-source')).toContainText('투구 3 · 좌완');
  await expect(page.locator('#timeline-time')).toContainText('-1.645s');
  await expect(page.locator('#height-output')).toHaveText('1.71 m');
  await page.locator('[data-delivery-event="1"]').click();
  await page.screenshot({path:'test-results/sample-3-left-knee.png',fullPage:true});
  await page.locator('[data-delivery-event="2"]').click();
  await page.locator('[data-view="delivery-side"]').click();
  await page.screenshot({path:'test-results/sample-3-left-plant.png',fullPage:true});
  await page.locator('[data-delivery-event="4"]').click();
  await page.locator('[data-view="delivery-front"]').click();
  await expect(page.locator('#camera-name')).toContainText('동작 검수');
  await page.screenshot({path:'test-results/delivery-left-release.png',fullPage:true});
  await page.locator('.simulation-column').screenshot({path:'test-results/sample-3-left-preview.png'});
  await page.locator('[data-pitcher="threequarter"]').click();
  await page.locator('[data-delivery-event="1"]').click();
  await page.screenshot({path:'test-results/delivery-compact.png',fullPage:true});
  await page.locator('#height-slider').fill('1.84');
  await expect(page.locator('#height-output')).toHaveText('1.84 m');
  expect(await page.evaluate(()=>localStorage.getItem('sinker-pitch-reading-v1'))).toBeNull();
  expect(errors).toEqual([]);
});
