/** 운동 이름으로 방식을 가린다. 어느 표시도 없으면 기본 보강이다. */
export function methodOf(title: string): ArmcareMethod {
  return (
    ARMCARE_METHODS.find((m) => m.titleMarker && title.includes(m.titleMarker)) ??
    ARMCARE_METHODS[0]
  );
}

