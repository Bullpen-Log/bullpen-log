/** 기본 목록의 음식이면 다른 이름까지 보고, 가장 잘 맞는 점수를 쓴다 */
function scoreOf(food: Food, query: string) {
  const aliases = food.source === 'basic' ? (ALIASES.get(food.id ?? '') ?? []) : [];
  return Math.max(...[food.name, ...aliases].map((n) => matchScore(n, query)));
}

/**
 * 음식 여러 묶음(내 음식 + 기본 목록)을 한 줄로 세운다.
 *
 * 내 음식에는 5점을 얹는다. 같은 정도로 맞으면 내가 만든 것이 먼저 나오되,
 * 이름이 딱 맞는 기본 음식을 어중간하게 맞는 내 음식이 밀어내지는 않게.
 */
export function rankFoods(foods: Food[], query: string, limit = 30): Food[] {
  const scored: { food: Food; score: number }[] = [];
  for (const food of foods) {
    const score = scoreOf(food, query);
    if (score > 0)
      scored.push({ food, score: score + (food.source === 'mine' ? 5 : 0) });
  }
  return scored
    .sort((a, b) => b.score - a.score || a.food.name.length - b.food.name.length)
    .slice(0, limit)
    .map((s) => s.food);
}

export function searchBasicFoods(query: string, limit = 30): Food[] {
  return rankFoods(BASIC_FOODS, query, limit);
}
