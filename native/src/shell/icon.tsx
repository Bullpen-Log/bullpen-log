/** 채움이 '켜짐'을 뜻하는 그림 — 네이비 · 다크에서도 fill 을 넘길 때만 채운다(찜 · 즐겨찾기 별이 늘 켜져 보이지 않게) */
const STATEFUL = new Set<string>(['star', 'heart']);

export type IconName =
  | keyof typeof ICONS
  | 'zone'
