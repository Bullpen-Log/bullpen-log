const apply = process.argv.includes('--yes');
const prisma = new PrismaClient({
  adapter: new PrismaPg({ connectionString: process.env.DATABASE_URL }),
});

const rows = await prisma.exerciseVideo.findMany({
  orderBy: { createdAt: 'asc' },
  select: { id: true, title: true, detailsFilledAt: true },
});

const byTitle = new Map(rows.map((r) => [r.title, r]));
const targets = [];
const alreadyFilled = [];
const notFound = [];

for (const [title, detail] of Object.entries(DETAILS)) {
  const row = byTitle.get(title);
  if (!row) {
    notFound.push(title);
    continue;
  }
  if (row.detailsFilledAt) {
    alreadyFilled.push(title);
    continue;
  }
  targets.push({ row, detail });
}

console.log(`채울 대상 ${targets.length}개`);
if (alreadyFilled.length)
  console.log(`이미 채워져 있어 건너뜀: ${alreadyFilled.join(', ')}`);
if (notFound.length) console.log(`⚠ DB에 없는 이름: ${notFound.join(', ')}`);

const stillEmpty = rows.filter((r) => !r.detailsFilledAt && !DETAILS[r.title]);
if (stillEmpty.length) {
  console.log(`\n⚠ 아직 내용이 없는데 이 목록에도 없는 운동 ${stillEmpty.length}개:`);
  for (const r of stillEmpty) console.log(`   - ${r.title}`);
}

if (!apply) {
  console.log('\n미리보기입니다. 실제로 저장하려면 --yes 를 붙여 다시 실행하세요.');
  await prisma.$disconnect();
  process.exit(0);
}

const now = new Date();
let done = 0;
for (const { row, detail } of targets) {
  await prisma.exerciseVideo.update({
    where: { id: row.id },
    data: { ...detail, detailsFilledAt: now },
  });
  done++;
}
console.log(`\n${done}개 저장 완료.`);
await prisma.$disconnect();
