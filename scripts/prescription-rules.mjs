/**
 * 세트·횟수·휴식을 정하는 규칙.
 *
 * 실제로 저장하는 fill-prescription.mjs 와, 결과를 눈으로 확인하는 스크립트가
 * 같은 규칙을 봐야 해서 여기로 따로 뺐다. 규칙을 한 곳에서만 고치면 된다.
 *
 * ── 기준 ──
 *
 * 세트는 모두 3세트. 횟수는 기본 10회, 파워는 5회(최대한 빠르게 내는 것이
 * 목적이라 많이 하면 속도가 떨어진다). 버티는 운동은 횟수 대신 초로 적는다.
 *
 * 휴식은 넉넉하게 잡았다. 짧게 쉬면 다음 세트에서 힘이 덜 나와 훈련 목적이
 * 흐려지기 때문이다. 무거울수록, 빠르게 힘을 내는 운동일수록 길게 준다.
 */

/* ──────────────── 시간으로 버티는 운동 가려내기 ──────────────── */

/*
 * 처음에는 설명에 '유지합니다'나 '버팁니다'가 있으면 버티기 운동으로 봤다.
 * 그런데 그 말들은 대부분 자세 안내다 — "허리를 중립으로 유지합니다",
 * "맨 아래에서 1초 버팁니다". 그래서 바벨 스쿼트와 푸쉬업까지 '30초 버티기'가
 * 됐다. 반복 운동 55개쯤이 그렇게 잘못 들어갔다.
 *
 * 지금은 제목을 본다. 버티는 운동은 이름에 그렇게 적혀 있다
 * (월 싯, 플랭크, 홀드, 아이소메트릭, 스트레치, 포즈…).
 * 설명에서는 '30초쯤 머뭅니다' 처럼 버티기에서만 쓰는 말만 쓴다.
 */

/** 이름에 이 낱말이 들어가면 시간으로 버티는 운동이다. */
const HOLD_NAME = /버티기|홀드|ISO|아이소메트릭|플랭크|데드행|월 싯|스트레치|포즈|롤링|디스트랙션/;

/** 몸을 굴려 푸는 이완 도구 — 모빌리티·회복에서만 버티기로 본다. */
const ROLLING_NAME = /폼롤러|마사지볼|LAX/;

/** 버티기에서만 쓰는 설명 문구 */
const HOLD_PHRASE = /초쯤 머|머뭅니다|초 유지/;

/** 이름만으로는 안 갈려서 직접 확인한 것 */
const HOLD_YES = new Set([
  '브레첼', // 누워서 비틀고 그대로 머무는 스트레치
  '90/90 페일즈·레일즈', // 늘린 자리에서 힘을 주고 버틴다
]);
const HOLD_NO = new Set([
  '플랭크 리치', // 플랭크 자세로 팔을 뻗었다 돌아오는 반복 운동
  '프론 밴드 쿼드 탠트럼 (플랭크 자세)', // 자세만 플랭크고 다리를 차는 반복 운동
  '토 홀드 스모 스쿼트', // '홀드'는 발가락을 잡는다는 뜻이고, 스쿼트는 반복한다
  '핸드 홀드 스플릿 스탠스 회전', // '홀드'는 손으로 붙잡는다는 뜻이다
  '롤링 (상체 시작)', // 몸을 굴려 넘어가는 동작을 반복한다
  '롤링 (하체 시작)',
]);

export function isHold(title, description, category) {
  if (HOLD_YES.has(title)) return true;
  if (HOLD_NO.has(title)) return false;
  if (HOLD_NAME.test(title)) return true;
  if (ROLLING_NAME.test(title) && (category === '모빌리티' || category === '회복 및 보강')) {
    return true;
  }
  return HOLD_PHRASE.test(description);
}

